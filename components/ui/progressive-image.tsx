import "@/components/ui/progressive-image.css"

import { useReducedMotion } from "motion/react"
import Image, { type ImageProps, type StaticImageData } from "next/image"
import {
  type AnimationEvent,
  useCallback,
  useLayoutEffect,
  useReducer,
  useRef,
} from "react"

import { useIsClient } from "@/lib/hooks/use-is-client"
import {
  IMAGE_PLACEHOLDERS,
  type PlaceholderKey,
} from "@/lib/image-placeholders"
import { isReducedMotion } from "@/lib/isReducedMotion"
import {
  type LoadPhase,
  mountEvent,
  nextLoadPhase,
  servedFromCache,
  settledEvent,
} from "@/lib/progressive-load"
import { cn } from "@/lib/utils"
import { useGlobalStates } from "@/providers/global-state-provider"

export type ProgressiveImageProps = Omit<
  ImageProps,
  "blurDataURL" | "onError" | "onLoad" | "placeholder" | "ref" | "src"
> & {
  /** A static import, so the real image always has a generated placeholder. */
  src: StaticImageData
  /** Key into lib/image-placeholders (generated by `just placeholders`). */
  placeholder: PlaceholderKey
  /** Classes for the wrapper box (positioning, hover effects). `className`
   *  goes on both images, so object-fit/position match exactly. */
  wrapperClassName?: string
  /** The real image failed (also when it failed before hydration). */
  onError?: () => void
}

const SHOWS_PLACEHOLDER: ReadonlySet<LoadPhase> = new Set([
  "pending",
  "loading",
  "revealing",
  "error",
])

/**
 * next/image with a blur-up reveal: a tiny blurred placeholder sits in the
 * same box, the real image fades in (opacity only) once it has loaded AND
 * decoded, then the placeholder unmounts. An image that is already complete
 * when the client first sees it (cached, or loaded before hydration — static
 * export means that can happen before React attaches any handler) is shown at
 * once with no fade. The server render keeps the real image visible, so a warm
 * reload never flashes the placeholder before hydration.
 */
export function ProgressiveImage({
  src,
  placeholder,
  className,
  wrapperClassName,
  onError,
  ...imageProps
}: ProgressiveImageProps) {
  const { animationPref } = useGlobalStates()
  const reduced = isReducedMotion(animationPref, useReducedMotion())
  // Server/hydration render → "pending" (real image visible until checked);
  // a purely client-side mount starts hidden behind the placeholder.
  const isClient = useIsClient()
  const [phase, dispatch] = useReducer(
    nextLoadPhase,
    isClient ? "loading" : "pending"
  )
  const onErrorRef = useRef(onError)
  useLayoutEffect(() => {
    onErrorRef.current = onError
  })
  // Reduced motion: swap instantly. Before paint, so no fade frame runs.
  useLayoutEffect(() => {
    if (reduced && phase === "revealing") dispatch("revealed")
  }, [reduced, phase])

  // Ref callback (React 19 cleanup form): runs once the <img> exists, which
  // after hydration may be long after it loaded, so read its state first and
  // only then listen. Native listeners, not next/image's onLoad/onError:
  // passing onError makes next/image re-assign `src` on mount, which restarts
  // an in-flight download.
  const attach = useCallback((img: HTMLImageElement | null) => {
    if (img === null) return
    const fail = () => {
      dispatch("failed")
      onErrorRef.current?.()
    }
    const initial = mountEvent(img)
    if (initial === "failed") fail()
    else dispatch(initial)

    const controller = new AbortController()
    const { signal } = controller
    const mountedAt = performance.now()
    img.addEventListener(
      "load",
      () => {
        // Reveal only once decoded, so the fade never starts on a blank
        // frame. A decode rejection (EncodingError) still reveals: the
        // browser can usually paint what it loaded.
        img
          .decode()
          .catch(() => undefined)
          .then(() => {
            if (signal.aborted) return
            const settled = settledEvent({
              elapsedMs: performance.now() - mountedAt,
              fromCache: servedFromCache(img.currentSrc),
            })
            dispatch(settled)
          })
      },
      { signal }
    )
    img.addEventListener("error", fail, { signal })
    return () => controller.abort()
  }, [])

  const onAnimationEnd = useCallback(
    (event: AnimationEvent<HTMLImageElement>) => {
      if (event.target === event.currentTarget) dispatch("revealed")
    },
    []
  )

  const fill = imageProps.fill === true
  return (
    <span
      className={cn(
        "progressive block",
        fill ? "absolute inset-0" : "relative",
        wrapperClassName
      )}
      data-state={phase}
    >
      {SHOWS_PLACEHOLDER.has(phase) ? (
        <Image
          alt=""
          aria-hidden
          className={cn("progressive__placeholder", className)}
          fill
          loading="eager"
          src={IMAGE_PLACEHOLDERS[placeholder]}
          unoptimized
        />
      ) : null}
      <Image
        {...imageProps}
        className={cn("progressive__img", !fill && "block", className)}
        onAnimationEnd={onAnimationEnd}
        ref={attach}
        src={src}
      />
    </span>
  )
}
